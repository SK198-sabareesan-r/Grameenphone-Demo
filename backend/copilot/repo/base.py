"""The data the Copilot needs, behind one interface.

Three implementations: DynamoDB (the real tables), local files (the seed JSON, for tests and as a fallback),
and a wrapper that uses DynamoDB and switches to the files when DynamoDB cannot be reached.
"""

from typing import Protocol


class DataUnavailable(Exception):
    """The data store could not be reached or refused the request (for example expired credentials)."""


class Repo(Protocol):
    name: str

    # reference data
    async def get_customer(self, mobile_number: str) -> dict | None: ...
    async def list_areas(self) -> list[dict]: ...
    async def get_area(self, area: str) -> dict | None: ...
    async def list_packs(self) -> list[dict]: ...
    async def get_pack(self, pack_id: str) -> dict | None: ...
    async def list_centres(self, area: str) -> list[dict]: ...

    # records the app writes
    async def list_open_tickets(self, customer_id: str) -> list[dict]: ...
    async def list_tickets(self) -> list[dict]: ...
    async def create_ticket(self, ticket: dict) -> bool:
        """Save a new ticket. Returns False, and saves nothing, if that ticket id already exists."""
        ...

    async def save_call(self, record: dict) -> None: ...
    async def list_calls(self) -> list[dict]: ...

    async def clear_runtime(self) -> None:
        """Delete what the app wrote (its tickets and all calls). Seeded data is kept."""
        ...

    def status(self) -> dict: ...
